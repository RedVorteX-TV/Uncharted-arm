#!/usr/bin/env python3
"""Assembles tools/fiber_stubs.S (x86-64 GNU as) into src/runtime_fiber_stubs.inc.

The .inc holds the stub bytes, each stub's offset and the places of the HOST_* placeholders, which
src/runtime_fiber.c replaces with FEXCore host-function stubs at run time. Needs binutils for
x86-64 (as, objcopy, nm); run it again whenever fiber_stubs.S changes."""
import os
import re
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'tools' / 'fiber_stubs.S'
OUTPUT = ROOT / 'src' / 'runtime_fiber_stubs.inc'
AS = os.environ.get('X86_AS', 'as')
OBJCOPY = os.environ.get('X86_OBJCOPY', 'objcopy')
NM = os.environ.get('X86_NM', 'nm')


def main():
    text = SOURCE.read_text()
    hosts = {name: int(value, 0) for name, value in re.findall(r'\.set\s+(HOST_\w+),\s*(0x[0-9a-fA-F]+)', text)}
    with tempfile.TemporaryDirectory() as tmp:
        obj, binary = Path(tmp) / 'stubs.o', Path(tmp) / 'stubs.bin'
        subprocess.run([AS, '--64', '-o', str(obj), str(SOURCE)], check=True)
        subprocess.run([OBJCOPY, '-O', 'binary', '-j', '.text', str(obj), str(binary)], check=True)
        code = binary.read_bytes()
        symbols = {}
        for line in subprocess.run([NM, str(obj)], check=True, capture_output=True, text=True).stdout.splitlines():
            parts = line.split()
            if len(parts) == 3 and parts[1] in 'Tt' and parts[2].startswith('stub_'):
                symbols[parts[2]] = int(parts[0], 16)
    patches = []
    for index, (name, value) in enumerate(sorted(hosts.items(), key=lambda item: item[1])):
        pattern = struct.pack('<Q', value)
        start = 0
        while (at := code.find(pattern, start)) >= 0:
            patches.append((at, name))
            start = at + 1
    if not patches:
        sys.exit('no HOST_* placeholders found')
    lines = ['/* Generated by tools/gen_fiber_stubs.py from tools/fiber_stubs.S; do not edit. */',
             f'static const unsigned char fiber_stub_code[{len(code)}]={{']
    for i in range(0, len(code), 16):
        lines.append('    ' + ','.join(f'0x{b:02x}' for b in code[i:i + 16]) + ',')
    lines.append('};')
    for name in ('stub_run', 'stub_run_with', 'stub_switch', 'stub_switch_with', 'stub_return', 'stub_start'):
        lines.append(f'#define FIBER_{name.upper()} {symbols[name]}u')
    lines.append('enum { ' + ', '.join(sorted(hosts, key=hosts.get)) + ', HOST_COUNT };')
    lines.append(f'static const struct {{ unsigned offset, host; }} fiber_stub_patches[{len(patches)}]={{')
    for at, name in sorted(patches):
        lines.append(f'    {{{at},{name}}},')
    lines.append('};')
    OUTPUT.write_text('\n'.join(lines) + '\n')
    print(f'{OUTPUT.relative_to(ROOT)}: {len(code)} bytes, {len(patches)} host calls')


if __name__ == '__main__':
    main()
