#!/usr/bin/env python3
"""Generates gpu/shim/vk_forwarders.cpp: C vkXxx entry points that forward to the renderer's
dispatcher (vulkan-hpp), for third-party C code (FidelityFX, FSR 4, Dear ImGui's non-loader paths,
fsr411) that calls vk* directly. The Bionic build links no libvulkan; these definitions satisfy
that code and route its calls through the one driver vk_driver_loader.cpp loaded.

usage: gen_vk_forwarders.py <vulkan_core.h> <names.txt> > gpu/shim/vk_forwarders.cpp
(names.txt: the vk* symbols libbbgpu.so leaves undefined: llvm-nm -D --undefined-only | grep ' vk')
"""
import re
import sys

header = open(sys.argv[1]).read()
names = sorted(set(l.split()[-1].split('@')[0] for l in open(sys.argv[2]) if l.strip()))
protos = {}
for m in re.finditer(r'VKAPI_ATTR\s+(.+?)\s+VKAPI_CALL\s+(vk\w+)\(([^;]*?)\);', header, re.S):
    protos[m.group(2)] = (m.group(1), ' '.join(m.group(3).split()))
out = ['// Generated by tools/android/gen_vk_forwarders.py - do not edit.',
       '// Forwarders from the C Vulkan entry points to the dispatcher (see the generator).',
       '#include "video_core/renderer_vulkan/vk_common.h"', '',
       '#define BB_FWD extern "C" __attribute__((visibility("hidden"))) VKAPI_ATTR', '']
for name in names:
    if name not in protos:
        sys.exit('no prototype for ' + name)
    ret, params = protos[name]
    args = []
    if params != 'void':
        for p in params.split(','):
            p = re.sub(r'\[.*?\]', '', p).strip()
            args.append(re.split(r'[\s*]+', p)[-1])
    call = 'VULKAN_HPP_DEFAULT_DISPATCHER.%s(%s)' % (name, ', '.join(args))
    out.append('BB_FWD %s VKAPI_CALL %s(%s) {' % (ret, name, params))
    out.append('    %s%s;' % ('' if ret == 'void' else 'return ', call))
    out.append('}')
print('\n'.join(out))
